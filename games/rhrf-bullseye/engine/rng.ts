export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, scale = 1, color = "#ffffff"): number {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? ["111", "101", "101", "101", "111"];
    for (let row = 0; row < 5; row++) for (let col = 0; col < 3; col++) {
      if (glyph[row][col] === "1") ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
    }
    cx += 4 * scale;
  }
  return cx - x - scale;
}
export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : text.length * 4 * scale - scale;
}
